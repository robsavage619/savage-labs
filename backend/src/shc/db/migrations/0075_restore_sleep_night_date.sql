-- Restore the night_date values that the 2026-07-25 WHOOP sleep sync overwrote.
--
-- 679817d added ts_in/ts_out to sync_sleep's ON CONFLICT DO UPDATE SET so a
-- completed record could no longer inherit the partial record's window. That was
-- the fix. It also added night_date on the reasoning that night_date derives from
-- ts_in — and that part was wrong in effect, because the two values were computed
-- by different generations of the ingest:
--
--   * rows written before the 2026-07-19 timezone fix got night_date from a UTC
--     truncation of `start`, which for a late-evening local bedtime rolls forward
--     to the WAKE date;
--   * _utc_to_local_date(start, offset) — today's code — returns the ONSET date.
--
-- night_date had never been in the UPDATE SET, so the old convention sat frozen in
-- 682 rows until one sync flipped every one of them a day earlier. The table
-- went from 921 wake-dated / 228 onset-dated to 324 / 908, and `sleep.night_date =
-- recovery.date` — a live join in dashboard.py and lab.py — fell from 60/60 to
-- 59/60 matches over the last 60 days.
--
-- This restores the pre-sync value for exactly those 682 rows, read out of a
-- snapshot taken before the sync. Every delta was exactly one day (old = new + 1);
-- the pairs are written out in full rather than as `+ INTERVAL 1 DAY` so a re-run
-- is a no-op and so the intended value of each row is auditable. Rows the sync did
-- not move are not listed and are not touched.
--
-- The companion code change drops night_date from the UPDATE SET, so a sync can no
-- longer re-apply this. It does NOT settle which convention is correct — new rows
-- still arrive onset-dated while history is wake-dated. That question is tracked in
-- DECISIONS.md and is deliberately out of scope here: this migration only undoes an
-- unintended mass rewrite.

